import streamlit as st

st.set_page_config(page_title="应急处置助手", page_icon="🚨", layout="wide")
st.title("🚨 宠物应急处置助手")
st.caption("紧急场景标准化处置步骤，争分夺秒拯救生命")

emergency_list = {
    "误食有毒物质": [
        "第一步：立即确认误食物品、剂量和时间，保留剩余物品/包装",
        "第二步：误食1小时内、非腐蚀性物品，可按体重喂稀释双氧水催吐",
        "第三步：腐蚀性物品（强酸强碱）禁止催吐，立即喂牛奶/蛋清保护黏膜",
        "第四步：第一时间携带样本送医，切勿自行喂解药",
        "⚠️ 提示：巧克力、葡萄、木糖醇、老鼠药均为高毒，务必立即就医"
    ],
    "中暑": [
        "第一步：立即转移至阴凉通风处，解开项圈",
        "第二步：用常温湿毛巾擦拭腹部、脚垫、腹股沟，用凉水缓慢冲淋",
        "第三步：禁止用冰水/冰块，防止血管收缩加重病情",
        "第四步：监测体温，降至39℃左右停止降温，立即送医",
        "⚠️ 提示：短鼻犬（法斗、巴哥）、肥胖宠物中暑风险极高"
    ],
    "外伤出血": [
        "第一步：用干净纱布/毛巾按压伤口止血，抬高患肢",
        "第二步：用生理盐水冲洗伤口，碘伏由内向外消毒",
        "第三步：伤口浅小可贴创可贴，伤口深、出血不止立即送医缝合",
        "第四步：金属致伤、伤口污染严重需注射破伤风",
        "⚠️ 提示：咬伤、抓伤需额外关注狂犬风险"
    ],
    "窒息/异物卡喉": [
        "第一步：打开口腔，查看异物位置，可视情况下小心取出",
        "第二步：无法取出时，小型宠物倒提拍打背部，大型宠物海姆立克法",
        "第三步：呼吸恢复后仍需就医检查气道损伤",
        "第四步：呼吸停止立即心肺复苏，同时送医",
        "⚠️ 提示：骨头、小球、塑料袋是常见卡喉异物，务必收好"
    ]
}

col1, col2 = st.columns(2)
for i, (name, steps) in enumerate(emergency_list.items()):
    if i % 2 == 0:
        with col1:
            with st.expander(f"🆘 {name}", expanded=False):
                for step in steps:
                    st.markdown(f"- {step}")
    else:
        with col2:
            with st.expander(f"🆘 {name}", expanded=False):
                for step in steps:
                    st.markdown(f"- {step}")

st.divider()
st.error("### ⚠️ 重要提示\n以上仅为紧急处置参考，所有紧急情况均建议尽快送医，切勿延误最佳治疗时机")
